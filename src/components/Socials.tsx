function Glyph({ social }: { social: SocialLink }) {
  if (social.imageUrl) {
    return (
      // eslint-disable-next-line @next/next/no-img-element
      <img
        src={social.imageUrl}
        alt=""
        width={18}
        height={18}
        className="h-[18px] w-[18px] object-contain"
      />
    );
  }
  if (social.maskUrl) {
    const mask = `url("${social.maskUrl}") center / contain no-repeat`;
    return (
      <span
        aria-hidden
        className="block h-[18px] w-[18px] bg-current"
        style={{ mask, WebkitMask: mask }}
      />
    );
  }
  return (
    <svg width="18" height="18" viewBox="0 0 24 24" fill="currentColor" aria-hidden>
      <path d={paths[social.icon] ?? paths.link} />
    </svg>
  );
}

export function Socials({
  socials,
  locale,
}: {
  socials: SocialLink[];
  locale: Locale;
}) {
  return (
    <div className="flex flex-wrap items-center gap-4 text-muted">
      {socials.map((social, i) => {
        const label = t(social.label, locale) || social.icon;
        return (
          <a
            key={i}
            href={social.url}
            target={/^https?:/.test(social.url) ? "_blank" : undefined}
            rel="noreferrer"
            aria-label={label}
            title={label}
            className="transition-colors hover:text-foreground"
          >
            <Glyph social={social} />
          </a>
        );
      })}
    </div>
  );
}
